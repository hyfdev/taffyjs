import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = resolve(repositoryDirectory, "packages/taffyjs-wasm/dist");
const wasmPath = resolve(outputDirectory, "taffyjs.wasm32-wasip1.wasm");
const generatedNodeLoaderPath = resolve(outputDirectory, "taffyjs.wasip1.cjs");
const payloadPath = resolve(outputDirectory, "taffyjs.wasm-base64.js");
const nodeLoaderPath = resolve(outputDirectory, "taffyjs.node.cjs");
const nodeBridgePath = resolve(outputDirectory, "taffyjs.node.js");
const browserBindingPath = resolve(outputDirectory, "taffyjs.browser.js");
const wasm = await readFile(wasmPath);

if (!wasm.subarray(0, 4).equals(Buffer.from([0x00, 0x61, 0x73, 0x6d]))) {
  throw new Error(`Expected a WebAssembly binary at ${wasmPath}`);
}

function replaceExactly(source, search, replacement, label) {
  const first = source.indexOf(search);
  const last = source.lastIndexOf(search);
  if (first === -1 || first !== last) {
    throw new Error(`Expected exactly one ${label} in the generated Node loader`);
  }
  return source.replace(search, replacement);
}

const payloadSource = `// Generated by tools/inline-wasm-package.mjs. Do not edit.
export default "${wasm.toString("base64")}";
`;

let nodeLoaderSource = (await readFile(generatedNodeLoaderPath, "utf8")).replaceAll("\r\n", "\n");

nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `/* auto-generated by NAPI-RS */`,
  `/* auto-generated by NAPI-RS */
/* Derived mechanically by tools/inline-wasm-package.mjs. Do not edit. */`,
  "napi-rs generated-file marker",
);
nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `const __nodeFs = require('node:fs')
const __nodePath = require('node:path')
const { WASI: __nodeWASI } = require('node:wasi')`,
  `const { Buffer: __nodeBuffer } = require('node:buffer')`,
  "Node filesystem and WASI imports",
);
nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `const {
  emnapiAsyncWorkPlugin: __emnapiAsyncWorkPlugin,`,
  `const {
  WASI: __nodeWASI,
  emnapiAsyncWorkPlugin: __emnapiAsyncWorkPlugin,`,
  "wasm-runtime import block",
);
nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `const __rootDir = __nodePath.parse(process.cwd()).root

const __wasi = new __nodeWASI({
  version: 'preview1',
  env: process.env,
  preopens: {
    [__rootDir]: __rootDir,
  }
})`,
  `module.exports = function loadBinding(__wasmBase64) {
const __wasi = new __nodeWASI({
  version: 'preview1',
})`,
  "Node WASI capability block and factory boundary",
);
nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `let __wasmFilePath = __nodePath.join(__dirname, 'taffyjs.wasm32-wasip1.wasm')
const __wasmDebugFilePath = __nodePath.join(__dirname, 'taffyjs.wasm32-wasip1.debug.wasm')

if (__nodeFs.existsSync(__wasmDebugFilePath)) {
  __wasmFilePath = __wasmDebugFilePath
} else if (!__nodeFs.existsSync(__wasmFilePath)) {
  const __wasiPackageEntry = require.resolve('@taffyjs/binding-wasm32-wasip1')
  const __packagedWasmFilePath = __nodePath.join(
    __nodePath.dirname(__wasiPackageEntry),
    'taffyjs.wasm32-wasip1.wasm',
  )
  if (!__nodeFs.existsSync(__packagedWasmFilePath)) {
    throw new Error(
      '@taffyjs/binding-wasm32-wasip1 is installed but is missing taffyjs.wasm32-wasip1.wasm.',
    )
  }
  __wasmFilePath = __packagedWasmFilePath
}

const __wasmFile = __nodeFs.readFileSync(__wasmFilePath)`,
  `const __wasmFile = __nodeBuffer.from(__wasmBase64, 'base64')`,
  "Node Wasm file-loading block",
);
nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `const __wasiRollbackRegistryKey =
  typeof __filename === 'string' ? __filename : __wasmFilePath`,
  `const __wasiRollbackRegistryKey = __filename`,
  "WASI rollback registry key",
);

for (const forbidden of [
  "node:fs",
  "node:path",
  "node:wasi",
  "process.env",
  "preopens",
  "__wasmFilePath",
  "@taffyjs/binding-wasm",
  "require('./taffyjs.wasm-base64",
]) {
  if (nodeLoaderSource.includes(forbidden)) {
    throw new Error(`Generated inline Node loader still contains ${JSON.stringify(forbidden)}`);
  }
}
for (const required of [
  "instantiateNapiModuleSync",
  "new __nodeWASI",
  "module.exports = function loadBinding(__wasmBase64)",
]) {
  if (!nodeLoaderSource.includes(required)) {
    throw new Error(`Generated inline Node loader is missing ${JSON.stringify(required)}`);
  }
}

nodeLoaderSource = replaceExactly(
  nodeLoaderSource,
  `module.exports = __napiModule.exports
module.exports.BindingTaffyTree = __napiModule.exports.BindingTaffyTree`,
  `return __napiModule.exports
}`,
  "Node binding export block",
);

const nodeBridgeSource = `// Generated by tools/inline-wasm-package.mjs. Do not edit.
import wasmBase64 from "./taffyjs.wasm-base64.js";
import loadBinding from "./taffyjs.node.cjs";

const binding = loadBinding(wasmBase64);
export const { BindingTaffyTree } = binding;
`;

const browserBindingSource = `// Generated by tools/inline-wasm-package.mjs. Do not edit.
import wasmBase64 from "./taffyjs.wasm-base64.js";
import { instantiate } from "./taffyjs.wasip1-deferred.js";

function decodeBase64(source) {
  if (Uint8Array.fromBase64) return Uint8Array.fromBase64(source);

  const binary = globalThis.atob(source);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}

const wasmModule = await WebAssembly.compile(decodeBase64(wasmBase64));
const binding = await instantiate(wasmModule);

export const { BindingTaffyTree } = binding;
`;

await Promise.all([
  writeFile(payloadPath, payloadSource),
  writeFile(nodeLoaderPath, nodeLoaderSource),
  writeFile(nodeBridgePath, nodeBridgeSource),
  writeFile(browserBindingPath, browserBindingSource),
]);

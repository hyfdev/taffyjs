function generateTypeScript() {
  const output = [
    "// Generated by tools/generate-numeric-families.mjs. Do not edit.",
    "",
    "export type EnumValue<Family extends Readonly<Record<string, number>>> = Family[keyof Family];",
  ];
  for (const [family, members] of Object.entries(families)) {
    output.push("", `export const ${family} = Object.freeze({`);
    for (const [value, member] of members.entries()) output.push(`  ${member}: ${value},`);
    output.push(`} as const);`, "", `export type ${family} = EnumValue<typeof ${family}>;`);
  }
  return `${output.join("\n")}\n`;
}

function generateRust() {
  const output = [
    "// Generated by tools/generate-numeric-families.mjs. Do not edit.",
    "#![allow(dead_code)]",
  ];
  for (const [family, members] of Object.entries(families)) {
    output.push(
      "",
      "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
      "#[repr(u8)]",
      `pub(crate) enum ${family}Code {`,
    );
    for (const [value, member] of members.entries()) output.push(`    ${member} = ${value},`);
    output.push(
      "}",
      "",
      `impl TryFrom<i64> for ${family}Code {`,
      "    type Error = ();",
      "",
      "    fn try_from(value: i64) -> Result<Self, Self::Error> {",
      "        match value {",
    );
    for (const [value, member] of members.entries()) {
      output.push(`            ${value} => Ok(Self::${member}),`);
    }
    output.push("            _ => Err(()),", "        }", "    }", "}");
  }
  return `${output.join("\n")}\n`;
}

function generateTypeTest() {
  const output = [
    "// Generated by tools/generate-numeric-families.mjs. Do not edit.",
    "",
    "import {",
  ];
  for (const family of Object.keys(families)) {
    output.push(`  ${family},`, `  type ${family} as ${family}Value,`);
  }
  output.push('} from "@taffyjs/node";');
  for (const [family, members] of Object.entries(families)) {
    output.push(
      "",
      `function narrow${family}(value: ${family}Value): void {`,
      "  switch (value) {",
    );
    for (const [value, member] of members.entries()) {
      output.push(
        `    case ${family}.${member}: {`,
        `      const narrowed: ${value} = value;`,
        "      void narrowed;",
        "      return;",
        "    }",
      );
    }
    output.push("  }", "  value satisfies never;", "}", "", `void narrow${family};`);
  }
  return `${output.join("\n")}\n`;
}

const outputs = [
  {
    path: resolve(root, "packages/taffyjs-node/src/generated/numeric-families.ts"),
    content: generateTypeScript(),
  },
  {
    path: resolve(root, "crates/taffyjs_binding/src/generated_numeric.rs"),
    content: generateRust(),
  },
  {
    path: resolve(root, "tests/taffyjs-node/tests/types/values/numeric-families.test-d.ts"),
    content: generateTypeTest(),
  },
];

if (process.argv.includes("--check")) {
  const stale = [];
  for (const output of outputs) {
    const actual = await readFile(output.path, "utf8").catch(() => null);
    if (actual !== output.content) stale.push(output.path);
  }
  if (stale.length > 0) {
    throw new Error(
      `Generated numeric families are stale:\n${stale.join("\n")}\nRun node tools/generate-numeric-families.mjs.`,
    );
  }
} else {
  await Promise.all(outputs.map((output) => writeFile(output.path, output.content)));
}
